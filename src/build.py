# Builds the single-page site: index.html = page shell + every source file, in MVC order.
import json, os
ORDER = ['snake', 'breakout', 'flappy', 'asteroids', 'missile', 'imitation', 'battleship']
read = lambda p: open(p, encoding='utf-8').read()
parts = ['engine.js']
cal = json.load(open('calibration.json')) if os.path.exists('calibration.json') else {}
js = [read('engine.js'), '/* ---------- Monte Carlo calibration table (generated by tools/calibrate.js) ---------- */\nCALIBRATION = ' + json.dumps(cal, separators=(',', ':')) + ';']
for g in ORDER:
    for part in ('model', 'ai'):
        js.append(read(f'games/{g}.{part}.js'))
js.append(read('ui.js'))
for g in ORDER:
    js.append(read(f'games/{g}.view.js'))
js.append(read('lab.js'))
html = read('head.html') + '<script src="https://cdn.jsdelivr.net/npm/peerjs@1.5.5/dist/peerjs.min.js"></script>\n<script>\n\'use strict\';\n' + '\n'.join(js) + '\nCab.init();\n</script>\n</body>\n</html>\n'
open('../index.html', 'w', encoding='utf-8').write(html)
print(len(html.splitlines()), 'lines', len(html) // 1024, 'KB')
